import logging
import os
import sys

sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))

import pandas as pd
import streamlit as st

from src.database import get_supabase_client

logger = logging.getLogger(__name__)

TABLE_NAME = "compliance_events"


@st.cache_data(ttl=300)
def fetch_events() -> pd.DataFrame:
    """Fetch all compliance events from Supabase and return as a DataFrame."""
    client = get_supabase_client()
    result = (
        client.table(TABLE_NAME)
        .select("*")
        .order("created_at", desc=True)
        .execute()
    )
    if not result.data:
        return pd.DataFrame()
    df = pd.DataFrame(result.data)
    if "effective_date" in df.columns:
        df["effective_date"] = pd.to_datetime(df["effective_date"], errors="coerce").dt.date
    if "created_at" in df.columns:
        df["created_at"] = pd.to_datetime(df["created_at"], errors="coerce")
    return df


def main() -> None:
    st.set_page_config(
        page_title="Global Compliance Radar",
        page_icon="📡",
        layout="wide",
    )

    st.title("📡 Global Compliance Radar")
    st.caption(
        "Automated AML/CFT regulatory intelligence. "
        "This dashboard is generated by AI and is for informational purposes only — "
        "it does not constitute legal advice."
    )

    # ── Sidebar filters ──
    st.sidebar.header("Filters")
    min_score = st.sidebar.slider(
        "Minimum Relevance Score",
        min_value=1,
        max_value=10,
        value=1,
    )

    # ── Fetch data ──
    try:
        df = fetch_events()
    except Exception:
        logger.exception("Failed to fetch events from Supabase")
        st.error("Could not connect to the database. Check your Supabase credentials.")
        return

    if df.empty:
        st.info("No compliance events found. Run the ingestion pipeline first.")
        return

    # ── Apply filters ──
    filtered = df[df["relevance_score"] >= min_score]

    jurisdictions = sorted(df["jurisdiction"].dropna().unique())
    selected_jurisdictions = st.sidebar.multiselect(
        "Jurisdiction",
        options=jurisdictions,
        default=jurisdictions,
    )
    filtered = filtered[filtered["jurisdiction"].isin(selected_jurisdictions)]

    statuses = sorted(df["status"].dropna().unique())
    selected_statuses = st.sidebar.multiselect(
        "Status",
        options=statuses,
        default=statuses,
    )
    filtered = filtered[filtered["status"].isin(selected_statuses)]

    # ── Enterprise teaser ──
    st.sidebar.markdown("---")
    st.sidebar.header("Enterprise Edition")
    st.sidebar.markdown(
        "- Multi-user authentication\n"
        "- Custom Regulatory Feeds\n"
        "- Automated Audit Logs\n"
        "- Slack/Teams Alerts"
    )
    st.sidebar.info("Want these features for your team? Contact us for an Enterprise license.")

    # ── Summary metrics ──
    col1, col2, col3 = st.columns(3)
    col1.metric("Total Events", len(filtered))
    col2.metric("Avg Relevance", f"{filtered['relevance_score'].mean():.1f}" if len(filtered) else "—")
    col3.metric("Jurisdictions", filtered["jurisdiction"].nunique())

    st.divider()

    # ── Data table ──
    display_columns = [
        "title",
        "jurisdiction",
        "status",
        "relevance_score",
        "effective_date",
        "summary",
        "recommended_action",
        "source_url",
        "created_at",
    ]
    display_columns = [c for c in display_columns if c in filtered.columns]

    st.dataframe(
        filtered[display_columns],
        width="stretch",
        hide_index=True,
        column_config={
            "title": st.column_config.TextColumn("Title", width="medium"),
            "jurisdiction": st.column_config.TextColumn("Jurisdiction", width="small"),
            "status": st.column_config.TextColumn("Status", width="small"),
            "relevance_score": st.column_config.ProgressColumn(
                "Relevance",
                width="small",
                min_value=1,
                max_value=10,
                format="%d",
            ),
            "effective_date": st.column_config.DateColumn("Effective Date", width="small"),
            "summary": st.column_config.TextColumn("Summary", width="large"),
            "recommended_action": st.column_config.TextColumn("Action", width="medium"),
            "source_url": st.column_config.LinkColumn("Source", width="small", display_text="Open"),
            "created_at": st.column_config.DatetimeColumn("Ingested", width="small", format="YYYY-MM-DD HH:mm"),
        },
    )


if __name__ == "__main__":
    main()
